/**
 * =========================================================================
 * Build & Bundle Tool: Dual-Compatible Google Apps Script Packer
 * File: build.js
 * =========================================================================
 * Usage: node build.js
 * Reads modular files (dataBase.js, cadEngine.js, dwgIo.js) and inlines them
 * into Index.dist.html or generates standalone single-file for Google Apps Script.
 */

const fs = require('fs');
const path = require('path');

const projectDir = path.join(__dirname, 'BOQ DWG of uPVC, Gi, Aluminium Windows, Ventilator, Door etc');

function bundle() {
    console.log('[BUILD] Packing modular fenestration CAD engine for Google Apps Script deployment...');

    const indexPath = path.join(projectDir, 'Index.html');
    const dbPath = path.join(projectDir, 'dataBase.js');
    const cadPath = path.join(projectDir, 'cadEngine.js');
    const dwgPath = path.join(projectDir, 'dwgIo.js');

    if (!fs.existsSync(indexPath)) {
        console.error('[BUILD] Index.html not found at: ' + indexPath);
        return;
    }

    let indexContent = fs.readFileSync(indexPath, 'utf-8');
    const dbContent = fs.existsSync(dbPath) ? fs.readFileSync(dbPath, 'utf-8') : '';
    const cadContent = fs.existsSync(cadPath) ? fs.readFileSync(cadPath, 'utf-8') : '';
    const dwgContent = fs.existsSync(dwgPath) ? fs.readFileSync(dwgPath, 'utf-8') : '';

    // Replace external script tags with bundled content
    const bundleScript = `
    <!-- BUNDLED ENGINE MODULES (AUTOGENERATED BY BUILD.JS) -->
    <script>
    /* --- dataBase.js --- */
    ${dbContent}
    </script>
    <script>
    /* --- cadEngine.js --- */
    ${cadContent}
    </script>
    <script>
    /* --- dwgIo.js --- */
    ${dwgContent}
    </script>
    `;

    // Replace script src tags
    let distContent = indexContent
        .replace(/<script\s+src="dataBase\.js"><\/script>/i, '')
        .replace(/<script\s+src="cadEngine\.js"><\/script>/i, '')
        .replace(/<script\s+src="dwgIo\.js"><\/script>/i, '');

    distContent = distContent.replace('</head>', `${bundleScript}\n</head>`);

    const outDistPath = path.join(projectDir, 'Index.dist.html');
    fs.writeFileSync(outDistPath, distContent, 'utf-8');
    console.log(`[BUILD] Successfully generated standalone Apps Script bundle: ${outDistPath} (${Math.round(distContent.length / 1024)} KB)`);
}

bundle();
